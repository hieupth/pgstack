#!/usr/bin/env bash
# setup.sh — one-shot first-boot bring-up:
#   secrets -> TLS certs -> tuned configs -> stack up -> admin console user.
# All generated secrets land in ./creds/ (chmod 600, gitignored).
#
# Usage: ./setup.sh <public-hostname> [tunner.sh options]
#   e.g. ./setup.sh pgsql01.hieupth.com
#        ./setup.sh pgsql01.hieupth.com --ram 3840 --cpu 3 --disk ssd --apps 4
# Extra args are forwarded to ./tunner.sh (hardware overrides — use them when
# auto-detection is wrong or unavailable, e.g. Proxmox LXC; --apps sizes the
# per-app connection budget).
#
# WG_IP (default 10.8.0.1) = this host's WireGuard address. PgBouncer binds to
# it, so the database is reachable ONLY from WireGuard peers (plus loopback).
#   override: WG_IP=10.9.0.1 ./setup.sh <hostname>
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$SCRIPT_DIR"

HOSTNAME_IN="${1:-}"
[ -n "$HOSTNAME_IN" ] || { echo "Usage: $0 <public-hostname> [tunner.sh options]" >&2; exit 2; }
# A leading dash means options were given before the hostname (e.g.
# `./setup.sh --ram 8192 host`) — HOSTNAME_IN would become "--ram" and
# sslgen would silently mint a cert with CN=--ram before tunner rejects.
case "$HOSTNAME_IN" in -*) echo "ERROR: hostname comes FIRST, before tunner options" >&2; exit 2;; esac
shift

# Root is refused on purpose: pgbouncer runs as YOUR uid (compose user: from
# .env) and refuses to start as root; and every secret written here would end
# up root-owned 0600, unreadable to the very uid that must read them.
if [ "$(id -u)" = "0" ]; then
  echo "ERROR: do not run $0 as root — pgbouncer cannot run as uid 0, and the" >&2
  echo "       secrets written here would be root-owned 0600. Run it as the" >&2
  echo "       operator user that owns this checkout; sudo is only used internally" >&2
  echo "       where needed (e.g. chown'ing ./password)." >&2
  exit 1
fi

WG_IP="${WG_IP:-10.8.0.1}"

# umask 022 on purpose while BUILDING (generated configs must stay container-
# readable); every secret gets explicit tight permissions below instead.
mkdir -p creds; umask 022

# ---- 0. .env for compose ----------------------------------------------------
# pgbouncer runs as YOUR uid (compose `user: ${PGBOUNCER_UID}`), so it can read
# 0600 files you own (userlist.txt, TLS key) — no world-readable secrets.
# Bind rule: use WG_IP only when it (a) exists on an interface AND (b) that
# interface is of type "wireguard" — an address on eth0/dummy would silently
# expose the port on a non-tunnel interface. A previously hand-set WG_BIND
# (something other than the 127.0.0.2 placeholder) is preserved, so a re-run
# while wg0 is briefly down cannot revert it.
detect_wg_bind() {
  local dev
  dev="$(ip -br addr show 2>/dev/null | grep -w "$WG_IP" | awk '{print $1}' | head -1)"
  if [ -n "$dev" ] && ip -d link show "$dev" 2>/dev/null | grep -qw wireguard; then
    printf '%s' "$WG_IP"
  else
    printf '127.0.0.2'
  fi
}
# `|| true` is load-bearing: on a fresh host .env does not exist and sed
# exits 2 — without it, set -e killed setup silently at this line.
# tr strips CR/trailing whitespace (a Windows-edited .env would otherwise
# round-trip a poisoned WG_BIND forever).
EXISTING_BIND="$(sed -n 's/^WG_BIND=//p' .env 2>/dev/null | tr -d '[:space:]' || true)"
if [ -n "$EXISTING_BIND" ] && [ "$EXISTING_BIND" != "127.0.0.2" ]; then
  WG_BIND="$EXISTING_BIND"
  echo ">> keeping existing WG_BIND=$WG_BIND from .env"
else
  WG_BIND="$(detect_wg_bind)"
  if [ "$WG_BIND" = "127.0.0.2" ]; then
    echo ">> NOTE: $WG_IP not found on any wireguard interface — binding 127.0.0.2 for now."
    echo ">>       Once WireGuard is up: set WG_BIND=$WG_IP in .env, then docker compose up -d."
  fi
fi
cat > .env <<EOF
# Generated by ./setup.sh — deployment-specific, gitignored.
PGBOUNCER_UID=$(id -u)
PGBOUNCER_GID=$(id -g)
WG_BIND=$WG_BIND
EOF

# ---- 1. superuser password -------------------------------------------------
# Nobody ever types this password (superuser access is `docker exec` over the
# trusted container-local unix socket), so it is GENERATED, never hand-edited.
# ./password is consumed by postgres ONLY at first initdb (fresh data/).
if [ -d data ]; then
  if grep -qx changeme password 2>/dev/null; then
    echo "ERROR: data/ exists AND ./password is 'changeme' — the initialized" >&2
    echo "       cluster's superuser password is the public placeholder. Either:" >&2
    echo "         a) delete data/ for a fresh start, or" >&2
    echo "         b) rotate it now:" >&2
    echo "            docker compose exec -T postgresql psql -U postgres \\" >&2
    echo "              -c \"ALTER USER postgres PASSWORD '<strong-password>'\"" >&2
    echo "            then write the same value to ./password and ./creds/postgres.pw." >&2
    exit 1
  fi
  echo ">> data/ exists — keeping ./password as-is (inert for an initialized cluster)"
else
  if [ ! -f password ] || grep -qx changeme password 2>/dev/null; then
    openssl rand -base64 24 > password
    cp password creds/postgres.pw
    chmod 600 creds/postgres.pw
    echo ">> generated superuser password -> ./password (copy: creds/postgres.pw)"
  fi
fi
[ -f password ] || openssl rand -base64 24 > password   # compose mounts it as a secret

# Lock ./password to uid 999 (postgres in-container) + 0600 when possible.
# Compose file-secrets are plain bind mounts: docker does NOT enforce
# mode/ownership, so we do. It stays readable to postgres at initdb, unreadable
# to everyone else. NOTE: chown AND chmod must run under the SAME sudo —
# after chown the operator is no longer the owner and a plain chmod gets EPERM.
if command -v sudo >/dev/null 2>&1 && sudo -n true 2>/dev/null; then
  sudo -n chown 999:999 password && sudo -n chmod 600 password \
    && echo ">> ./password locked to 0600 uid 999 (sudo)"
else
  echo ">> WARN: no root/sudo here — ./password stays 0644." >&2
  echo ">>       Inert for an initialized cluster (break-glass is docker exec), but on a" >&2
  echo ">>       multi-user host run: sudo chown 999:999 password && sudo chmod 600 password" >&2
fi

# ---- 2. pgbouncer auth_file (SCRAM verifiers only — starts empty) ----------
[ -f userlist.txt ] || : > userlist.txt
chmod 600 userlist.txt   # pgbouncer runs as your uid (compose user:) — 600 is enough

# ---- 2b. CA-key migration (old layout kept it inside the mounted ./ssl) -----
# Runs on EVERY setup so a repo upgrade can never skip it: leaving the CA
# signing key inside ./ssl hands it to the pgbouncer container (dir is mounted).
# NEVER overwrite an existing ssl-ca/ca-key.pem (e.g. an old ssl/ restored
# over a migrated tree) — quarantine the stray instead, nothing is lost.
if [ -f ssl/ca-key.pem ]; then
  mkdir -p ssl-ca && chmod 700 ssl-ca
  if [ -f ssl-ca/ca-key.pem ]; then
    mv ssl/ca-key.pem "ssl-ca/ca-key.pem.stray-$(date -u +%Y%m%d%H%M%S)"
    echo ">> WARN: ssl/ca-key.pem AND ssl-ca/ca-key.pem both existed — stray quarantined" >&2
    echo ">>       in ssl-ca/*.stray-*; compare with ca.pem and delete the wrong one." >&2
  else
    mv ssl/ca-key.pem ssl-ca/ca-key.pem
    echo ">> migrated ssl/ca-key.pem -> ssl-ca/ca-key.pem (outside the container mount)"
  fi
  chmod 600 ssl-ca/ca-key.pem*
fi

# ---- 3. TLS certs ------------------------------------------------------------
# SANs: the WireGuard address (remote apps), 127.0.0.1 + localhost (local admin
# and SSH tunnels) — sslmode=verify-full works on every access path.
if [ ! -f ssl/ca.pem ]; then
  ./sslgen.sh "$HOSTNAME_IN" "$WG_IP" 127.0.0.1 localhost
else
  echo ">> ssl/ exists — skipping sslgen"
  echo ">>       (add SANs later: ./sslgen.sh <host> $WG_IP 127.0.0.1 localhost --force)"
fi

# ---- 4. tuned configs --------------------------------------------------------
./tunner.sh "$@"

# ---- 5. stack up ---------------------------------------------------------------
# pgstacknet is declared `external: true` in compose.yml (keeps it survive
# `docker compose down`); create it if this is a fresh host.
docker network create pgstacknet 2>/dev/null || true
docker compose up -d --wait

# Harden: no role may CONNECT to the admin databases (superuser/owner exempt).
# App databases get the same treatment in ./cred.sh; without this, any app
# role could connect to `postgres` (catalog metadata + temp-table disk abuse).
docker compose exec -T postgresql psql -U postgres -q \
  -c 'REVOKE CONNECT ON DATABASE postgres, template1 FROM PUBLIC'

# ---- 6. admin console user -----------------------------------------------------
# Provision ONCE: a re-run of setup.sh must not silently rotate the console
# password (monitoring/automation may hold it). Rotate deliberately with
# `./cred.sh pgbouncer_admin`.
if docker compose exec -T postgresql psql -U postgres -tAc \
    "SELECT 1 FROM pg_roles WHERE rolname = 'pgbouncer_admin'" | grep -q 1; then
  echo ">> pgbouncer_admin already provisioned — not rotating (./cred.sh pgbouncer_admin to rotate)"
else
  ./cred.sh pgbouncer_admin
fi

cat <<'EOF'

Done.
  Admin console : psql -h 127.0.0.1 -p 6432 -U pgbouncer_admin pgbouncer
                  (password: cat creds/pgbouncer_admin.pw)
  Add an app    : ./cred.sh <role> [<db>]     e.g. ./cred.sh zitadel zitadel
  Remote apps   : WireGuard only. Bring up wg0, set WG_BIND=<wg-ip> in .env,
                  then: docker compose up -d
                  DSN: postgresql://<role>:<pw>@<wg-ip>:6432/<db>?sslmode=verify-full&sslrootcert=<ca.pem>

NOT DONE YET — backups do not exist until you do this (see README Backups):
  1. crontab -e   (as THIS user, not root) and add:
     15 3 * * *  cd <this-dir> && mkdir -p backups && ./backup.sh >> backups/backup.log 2>&1
  2. Copy off-host ENCRYPTED (globals dumps contain SCRAM verifiers), and
     bundle creds/ + userlist.txt + ssl-ca/ + .env with them — a host-loss DR
     needs all of those, not just the dumps.
  3. Calendar the cert expiry: openssl x509 -in ssl/cert.pem -noout -enddate
EOF
